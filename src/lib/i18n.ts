export function importCustomLanguagePack(name: string, rawJson: string): { success: boolean; count: number; packId?: string; error?: string } {
  try {
    const parsed = JSON.parse(rawJson);
    let dict: Record<string, string> = {};

    if (parsed.translations && typeof parsed.translations === 'object' && !Array.isArray(parsed.translations)) {
      dict = parsed.translations;
    } else if (typeof parsed === 'object' && !Array.isArray(parsed)) {
      dict = parsed;
    } else {
      return { success: false, count: 0, error: 'Invalid JSON format: An object with translation key-values was expected.' };
    }

    const cleanTranslations: Record<string, string> = {};
    for (const [k, v] of Object.entries(dict)) {
      if (!k.startsWith('_') && typeof v === 'string') {
        cleanTranslations[k] = v;
      }
    }

    const count = Object.keys(cleanTranslations).length;
    if (count === 0) {
      return { success: false, count: 0, error: 'No valid translation keys were found in this JSON file.' };
    }

    const metaName = (parsed._metadata && typeof parsed._metadata.language_name === 'string') ? parsed._metadata.language_name : name;
    const packId = `lang_pack_${Date.now()}`;
    const newPack: CustomLanguagePack = {
      id: packId,
      name: metaName || 'Custom Language Pack',
      code: parsed._metadata?.language_code || 'custom',
      author: parsed._metadata?.author || '',
      version: parsed._metadata?.version || '1.0',
      description: parsed._metadata?.description || '',
      updatedAt: new Date().toISOString(),
      count,
      translations: cleanTranslations
    };

    const existing = getCustomLanguagePacks();
    const updated = [newPack, ...existing.filter(p => p.id !== packId)];
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('socdof_custom_lang_packs', JSON.stringify(updated));
    }

    setActiveCustomPack(packId);
    return { success: true, count, packId };
  } catch (err) {
    return { success: false, count: 0, error: `JSON Parse error: ${String(err)}` };
  }
}

const listeners = new Set<(lang: LanguageCode) => void>();

export function subscribeLanguageChange(listener: (lang: LanguageCode) => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function setLanguage(lang: LanguageCode) {
  if (lang !== 'en' && lang !== 'de' && lang !== 'fr' && lang !== 'es') return;
  currentLang = lang;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
  if (typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem('socdof_language', lang);
      localStorage.setItem('socdof_language_initialized', 'true');
    } catch {}
  }
  listeners.forEach(cb => {
    try {
      cb(lang);
    } catch {}
  });
}

export function getLanguage(): LanguageCode {
  if (typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem('socdof_language');
      if (saved === 'en' || saved === 'de' || saved === 'fr' || saved === 'es') {
        currentLang = saved as LanguageCode;
        return saved as LanguageCode;
      }
    } catch {}
  }
  return currentLang;
}

export function useLanguage(): LanguageCode {
  const [lang, setLang] = useState<LanguageCode>(getLanguage());

  useEffect(() => {
    const unsubscribe = subscribeLanguageChange((newLang) => {
      setLang(newLang);
    });
    return unsubscribe;
  }, []);

  return lang;
}

export function t(key: string, langOverride?: LanguageCode, fallback?: string): string {
  if (!langOverride && activeCustomTranslations && activeCustomTranslations[key]) {
    return activeCustomTranslations[key];
  }
  const active = langOverride || getLanguage();
  const dict = translations[active] || translations.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return fallback || key;
}

export function formatSystemTime(
  dateInput: Date | string | number = new Date(),
  showSeconds: boolean = true,
  timeZone?: string
): string {
  try {
    const d = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
    if (!d || isNaN(d.getTime())) return '';
    const options: Intl.DateTimeFormatOptions = {
      hour: '2-digit',
      minute: '2-digit',
      ...(showSeconds ? { second: '2-digit' } : {}),
      ...(timeZone ? { timeZone } : {})
    };
    return d.toLocaleTimeString([], options);
  } catch {
    const d = new Date(dateInput);
    return d.toLocaleTimeString([], showSeconds ? { hour: '2-digit', minute: '2-digit', second: '2-digit' } : { hour: '2-digit', minute: '2-digit' });
  }
}

export function formatSystemDate(
  dateInput: Date | string | number = new Date(),
  format: string = 'DD.MM.YYYY',
  timeZone?: string
): string {
  try {
    const d = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
    if (!d || isNaN(d.getTime())) return String(dateInput);

    if (timeZone) {
      try {
        const formatter = new Intl.DateTimeFormat('en-US', {
          timeZone,
          year: 'numeric',
          month: '2-digit',
          day: '2-digit'
        });
        const parts = formatter.formatToParts(d);
        const day = parts.find(p => p.type === 'day')?.value || String(d.getDate()).padStart(2, '0');
        const month = parts.find(p => p.type === 'month')?.value || String(d.getMonth() + 1).padStart(2, '0');
        const year = parts.find(p => p.type === 'year')?.value || String(d.getFullYear());

        switch (format) {
          case 'YYYY-MM-DD':
            return `${year}-${month}-${day}`;
          case 'MM/DD/YYYY':
            return `${month}/${day}/${year}`;
          case 'DD.MM.YYYY':
          default:
            return `${day}.${month}.${year}`;
        }
      } catch {
        // Fallback to local parsing below
      }
    }

    const day = String(d.getDate()).padStart(2, '0');
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const year = String(d.getFullYear());

    switch (format) {
      case 'YYYY-MM-DD':
        return `${year}-${month}-${day}`;
      case 'MM/DD/YYYY':
        return `${month}/${day}/${year}`;
      case 'DD.MM.YYYY':
      default:
        return `${day}.${month}.${year}`;
    }
  } catch {
    return String(dateInput);
  }
}

/**
 * Formats keyboard shortcut strings according to language or user-configured modifier preference (Strg / Ctrl / Cmd)
 * Example: formatShortcut('Ctrl+K', 'de') => 'Strg+K'
 */
export function formatShortcut(
  shortcut: string,
  lang: LanguageCode = 'de',
  style: 'auto' | 'strg' | 'ctrl' | 'cmd' = 'auto'
): string {
  if (!shortcut) return '';

  const isMac = typeof navigator !== 'undefined' && /Mac|iPhone|iPod|iPad/i.test(navigator.platform || navigator.userAgent || '');

  let targetStyle: 'strg' | 'ctrl' | 'cmd' = 'ctrl';
  if (style === 'strg') {
    targetStyle = 'strg';
  } else if (style === 'ctrl') {
    targetStyle = 'ctrl';
  } else if (style === 'cmd') {
    targetStyle = 'cmd';
  } else {
    // auto mode
    if (isMac && lang !== 'de') {
      targetStyle = 'cmd';
    } else if (lang === 'de') {
      targetStyle = 'strg';
    } else {
      targetStyle = 'ctrl';
    }
  }

  let res = shortcut;

  if (targetStyle === 'cmd') {
    res = res
      .replace(/\b(Ctrl|Strg)\b/g, '⌘')
      .replace(/\bAlt\b/g, '⌥')
      .replace(/\b(Shift|Umschalt)\b/g, '⇧')
      .replace(/⌘\+/g, '⌘')
      .replace(/⌥\+/g, '⌥')
      .replace(/⇧\+/g, '⇧');
    return res;
  }

  if (targetStyle === 'strg') {
    res = res
      .replace(/\bCtrl\b/g, 'Strg')
      .replace(/\b⌘\b/g, 'Strg')
      .replace(/\bShift\b/g, 'Umschalt')
      .replace(/\bSpace\b/g, 'Leertaste')
      .replace(/\bLeft\b/g, 'Links')
      .replace(/\bRight\b/g, 'Rechts');
    return res;
  }

  // default 'ctrl'
  res = res
    .replace(/\bStrg\b/g, 'Ctrl')
    .replace(/\b⌘\b/g, 'Ctrl')
    .replace(/\bUmschalt\b/g, 'Shift')
    .replace(/\bLeertaste\b/g, 'Space')
    .replace(/\bLinks\b/g, 'Left')
    .replace(/\bRechts\b/g, 'Right');
  return res;
}


