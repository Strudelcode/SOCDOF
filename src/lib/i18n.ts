let currentLang: LanguageCode = (() => {
  if (typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem('socdof_language');
      if (saved === 'en' || saved === 'de' || saved === 'fr' || saved === 'es') {
        return saved as LanguageCode;
      }
    } catch {}
  }
  return 'en';
})();

const listeners = new Set<(lang: LanguageCode) => void>();

export function subscribeLanguageChange(listener: (lang: LanguageCode) => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function setLanguage(lang: LanguageCode) {
  if (lang !== 'en' && lang !== 'de' && lang !== 'fr' && lang !== 'es') return;
  currentLang = lang;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
  if (typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem('socdof_language', lang);
      localStorage.setItem('socdof_language_initialized', 'true');
    } catch {}
  }
  listeners.forEach(cb => {
    try {
      cb(lang);
    } catch {}
  });
}

export function getLanguage(): LanguageCode {
  if (typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem('socdof_language');
      if (saved === 'en' || saved === 'de' || saved === 'fr' || saved === 'es') {
        currentLang = saved as LanguageCode;
        return saved as LanguageCode;
      }
    } catch {}
  }
  return currentLang;
}

export function useLanguage(): LanguageCode {
  const [lang, setLang] = useState<LanguageCode>(getLanguage());

  useEffect(() => {
    const unsubscribe = subscribeLanguageChange((newLang) => {
      setLang(newLang);
    });
    return unsubscribe;
  }, []);

  return lang;
}

export function t(key: string, langOverride?: LanguageCode, fallback?: string): string {
  const active = langOverride || getLanguage();
  const dict = translations[active] || translations.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return fallback || key;
}

export function formatSystemTime(
  dateInput: Date | string | number = new Date(),
  showSeconds: boolean = true,
  timeZone?: string
): string {
  try {
    const d = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
    if (!d || isNaN(d.getTime())) return '';
    const options: Intl.DateTimeFormatOptions = {
      hour: '2-digit',
      minute: '2-digit',
      ...(showSeconds ? { second: '2-digit' } : {}),
      ...(timeZone ? { timeZone } : {})
    };
    return d.toLocaleTimeString([], options);
  } catch {
    const d = new Date(dateInput);
    return d.toLocaleTimeString([], showSeconds ? { hour: '2-digit', minute: '2-digit', second: '2-digit' } : { hour: '2-digit', minute: '2-digit' });
  }
}

export function formatSystemDate(
  dateInput: Date | string | number = new Date(),
  format: string = 'DD.MM.YYYY',
  timeZone?: string
): string {
  try {
    const d = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
    if (!d || isNaN(d.getTime())) return String(dateInput);

    if (timeZone) {
      try {
        const formatter = new Intl.DateTimeFormat('en-US', {
          timeZone,
          year: 'numeric',
          month: '2-digit',
          day: '2-digit'
        });
        const parts = formatter.formatToParts(d);
        const day = parts.find(p => p.type === 'day')?.value || String(d.getDate()).padStart(2, '0');
        const month = parts.find(p => p.type === 'month')?.value || String(d.getMonth() + 1).padStart(2, '0');
        const year = parts.find(p => p.type === 'year')?.value || String(d.getFullYear());

        switch (format) {
          case 'YYYY-MM-DD':
            return `${year}-${month}-${day}`;
          case 'MM/DD/YYYY':
            return `${month}/${day}/${year}`;
          case 'DD.MM.YYYY':
          default:
            return `${day}.${month}.${year}`;
        }
      } catch {
        // Fallback to local parsing below
      }
    }

    const day = String(d.getDate()).padStart(2, '0');
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const year = String(d.getFullYear());

    switch (format) {
      case 'YYYY-MM-DD':
        return `${year}-${month}-${day}`;
      case 'MM/DD/YYYY':
        return `${month}/${day}/${year}`;
      case 'DD.MM.YYYY':
      default:
        return `${day}.${month}.${year}`;
    }
  } catch {
    return String(dateInput);
  }
}

